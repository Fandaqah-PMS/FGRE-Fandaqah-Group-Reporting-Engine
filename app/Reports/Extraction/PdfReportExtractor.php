<?php

namespace App\Reports\Extraction;

use App\Models\ReportDocument;
use App\Reports\Extraction\Pdf\FrontOfficeTrialBalanceReader;
use App\Reports\Extraction\Pdf\GuestTrialBalanceReader;
use App\Reports\Extraction\Pdf\LedgerTrialBalanceReader;
use App\Reports\Extraction\Pdf\ManagerFlashReader;
use App\Reports\Extraction\Pdf\PdfReportReader;
use App\Reports\Extraction\Pdf\PdfText;
use App\Reports\Extraction\Pdf\PdfToText;

/**
 * Reads a report PDF without AI: pdftotext extracts the text on the server, then the reader
 * for the report's layout turns it into the canonical shape. A layout no reader knows is
 * not guessed: the document fails with a clear reason so a reader can be added.
 *
 * Add a PMS or report: write a PdfReportReader, register it in READERS (most specific
 * first) and test it against a real sample.
 */
class PdfReportExtractor implements ReportExtractor
{
    /** @var list<class-string<PdfReportReader>> */
    public const READERS = [
        GuestTrialBalanceReader::class,
        ManagerFlashReader::class,
        LedgerTrialBalanceReader::class,
        FrontOfficeTrialBalanceReader::class,
    ];

    public function __construct(private readonly PdfToText $pdfToText) {}

    public function extract(ReportDocument $document): ExtractionResult
    {
        $text = $document->mime_type === 'text/plain'
            ? new PdfText($document->contents())
            : $this->pdfToText->read($document->contents());

        return $this->fromText($text);
    }

    public function fromText(PdfText $text): ExtractionResult
    {
        if ($text->isEmpty()) {
            throw new ExtractionFailed('The PDF has no text (a scan or a photo). Ask the hotel to send the PDF generated by the PMS.');
        }

        foreach (self::READERS as $class) {
            $reader = app($class);
            if ($reader->matches($text)) {
                return new ExtractionResult($reader->read($text), 'pdf:'.$reader->key());
            }
        }

        $first = collect($text->lines())->map(fn ($l) => trim(preg_replace('/\s{2,}/u', ' · ', $l)))->filter()->take(3)->implode(' | ');

        throw new ExtractionFailed("This report layout is not supported yet ({$first}). Send a sample so a reader can be added.");
    }
}
